"""Shared helpers for the validation scripts: output folders and Markdown tables."""

from __future__ import annotations

import os
from collections.abc import Sequence
from pathlib import Path

os.environ.setdefault("MPLBACKEND", "Agg")
# The studies run many tiny array operations; BLAS threads only add contention.
for _var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_var, "1")

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "validation" / "results"
FIGURES = ROOT / "docs" / "figures"
RESULTS.mkdir(parents=True, exist_ok=True)
FIGURES.mkdir(parents=True, exist_ok=True)


def fmt(x: object, digits: int = 4) -> str:
    """Numbers in a compact, stable format (scientific notation below 1e-3)."""
    if isinstance(x, bool) or not isinstance(x, int | float):
        return str(x)
    if isinstance(x, int):
        return str(x)
    if x == float("inf"):
        return "∞"
    if x != 0 and abs(x) < 1e-3:
        return f"{x:.{digits - 1}e}"
    return f"{x:.{digits}g}"


def bounded(x: float, floor: float = 0.01, digits: int = 3) -> object:
    """``x`` rounded, or ``"< floor"`` below it.

    Used for quantities that are essentially zero but whose exact tiny value depends on
    where an optimiser stops on a flat likelihood (it can differ between CPUs), so that
    results still reproduce byte for byte everywhere.
    """
    return f"< {floor:g}" if x < floor else round(x, digits)


def table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(fmt(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def write_result(
    name: str, title: str, sections: Sequence[tuple[str, str]], script: str | None = None
) -> Path:
    """Write ``validation/results/<name>.md`` with a header saying how it was generated."""
    path = RESULTS / f"{name}.md"
    body = [
        f"# {title}\n",
        f"Generated by `validation/{script or name}.py`; do not edit by hand.\n",
    ]
    for heading, text in sections:
        body.append(f"## {heading}\n\n{text}")
    path.write_text("\n".join(body))
    return path
